// Index the documentation the installed XState packages ship.
// xstate ships its docs under docs/ and @xstate/effect ships a README, both at
// the version the catalog pins, so this writes two indexes and copies nothing.
// It reads only local files.
//
//   node scripts/agent-sources/index-xstate-docs.ts           write .agent_sources/xstate/index.md and xstate-effect/index.md
//   node scripts/agent-sources/index-xstate-docs.ts --check   fail when either file does not match the installed packages

import { NodeRuntime, NodeServices } from "@effect/platform-node";
import {
  Array,
  Effect,
  FileSystem,
  flow,
  Layer,
  Logger,
  Option,
  Order,
  Path,
  Predicate,
  Record,
  Runtime,
  Schema,
  String,
} from "effect";
import { Command, Flag } from "effect/cli";
import { Yaml } from "effect/encoding";

import { replaceFile } from "../../packages/cli/src/atomic-write.ts";
import { escapeCell, headingsOf, topicTable } from "./markdown.ts";

// The workspace that depends on XState; pnpm links its packages into its node_modules.
const OWNER = "packages/core";
const REGENERATE = "node scripts/agent-sources/index-xstate-docs.ts";
const GENERATED =
  "Generated by `scripts/agent-sources/index-xstate-docs.ts` from the installed package. Do not edit it; `pnpm run check:xstate-docs` fails when it is stale.";

// Each expected failure logs its own message once (see the command below), so the runtime is told not to print it again.
class XStateNotInstalled extends Schema.TaggedError<XStateNotInstalled>()("XStateNotInstalled", {
  pkg: Schema.String,
  reason: Schema.String,
}) {
  override readonly [Runtime.errorReported] = false;
  override get message() {
    return `${this.reason}; run pnpm install`;
  }
}

class WorkspaceUnreadable extends Schema.TaggedError<WorkspaceUnreadable>()("WorkspaceUnreadable", {
  reason: Schema.String,
}) {
  override readonly [Runtime.errorReported] = false;
  override get message() {
    return `pnpm-workspace.yaml is not valid YAML: ${this.reason}`;
  }
}

class StaleXStateIndex extends Schema.TaggedError<StaleXStateIndex>()("StaleXStateIndex", {
  files: Schema.Array(Schema.String),
}) {
  override readonly [Runtime.errorReported] = false;
  override get message() {
    return `${Array.join(this.files, ", ")} do not match the installed XState packages; run ${REGENERATE}`;
  }
}

const decodeManifest = Schema.decodeEffect(
  Schema.fromJsonString(
    Schema.Struct({ dependencies: Schema.Record(Schema.String, Schema.String) }),
  ),
);
const decodeInstalled = Schema.decodeEffect(
  Schema.fromJsonString(Schema.Struct({ version: Schema.String })),
);
const decodeWorkspace = Schema.decodeUnknownEffect(
  Schema.Struct({ catalog: Schema.Record(Schema.String, Schema.String) }),
);

const QUOTED = /^(['"])(.*)\1$/;

// The lines between a page's opening and closing `---`, or none when it has no frontmatter.
const frontmatterOf = (lines: ReadonlyArray<string>) =>
  Option.filter(Array.head(lines), (first) => first === "---").pipe(
    Option.flatMap(() => {
      const rest = Array.drop(lines, 1);
      return Option.map(
        Array.findFirstIndex(rest, (line) => line === "---"),
        (end) => Array.take(rest, end),
      );
    }),
  );

// A frontmatter value, unquoted, or none.
const field = (frontmatter: Option.Option<ReadonlyArray<string>>, key: string) =>
  Option.flatMap(frontmatter, (lines) =>
    Array.findFirst(lines, String.startsWith(`${key}:`)).pipe(
      Option.map(flow(String.slice(key.length + 1), String.trim, String.replace(QUOTED, "$2"))),
    ),
  );

interface Output {
  readonly file: string;
  readonly text: string;
}

const indexXStateDocs = Effect.fn("indexXStateDocs")(function* ({ check }: { check: boolean }) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const repo = yield* path.fromFileUrl(new URL("../../", import.meta.url));
  const manifest = yield* fs
    .readFileString(path.join(repo, OWNER, "package.json"))
    .pipe(Effect.flatMap(decodeManifest));
  const workspaceYaml = yield* fs.readFileString(path.join(repo, "pnpm-workspace.yaml"));
  const { catalog } = yield* Effect.try({
    try: () => Yaml.parse(workspaceYaml),
    catch: (cause) =>
      new WorkspaceUnreadable({
        reason: Predicate.isError(cause) ? cause.message : "unknown error",
      }),
  }).pipe(Effect.flatMap(decodeWorkspace));

  // The version the owning workspace pins, through the workspace catalog when it says "catalog:".
  const pinOf = (name: string) =>
    Record.get(manifest.dependencies, name).pipe(
      Option.flatMap((pin) => (pin === "catalog:" ? Record.get(catalog, name) : Option.some(pin))),
    );

  // The installed copy of a package the owning workspace pins, checked against that pin.
  const installed = Effect.fn("installed")(function* (name: string) {
    const dir = yield* Effect.findFirst(
      [path.join(repo, OWNER, "node_modules", name), path.join(repo, "node_modules", name)],
      (candidate) => fs.exists(path.join(candidate, "package.json")),
    ).pipe(
      Effect.flatMap((found) =>
        Effect.fromOption(
          found,
          () =>
            new XStateNotInstalled({ pkg: name, reason: `${name} is not installed for ${OWNER}` }),
        ),
      ),
    );
    const { version } = yield* fs
      .readFileString(path.join(dir, "package.json"))
      .pipe(Effect.flatMap(decodeInstalled));
    const pin = pinOf(name);
    if (!Option.contains(pin, version)) {
      return yield* new XStateNotInstalled({
        pkg: name,
        reason: `${OWNER} pins ${name}@${Option.getOrElse(pin, () => "nothing")} but ${version} is installed`,
      });
    }
    return { name, version, dir, location: path.relative(repo, dir) };
  });

  const xstate = yield* installed("xstate");
  const effect = yield* installed("@xstate/effect");

  const docsDir = path.join(xstate.dir, "docs");
  const listing = yield* fs.readDirectory(docsDir);
  const pages = Array.sort(Array.filter(listing, String.endsWith(".md")), Order.String);
  const rows = yield* Effect.forEach(
    pages,
    Effect.fnUntraced(function* (page) {
      const text = yield* fs.readFileString(path.join(docsDir, page));
      const lines = String.split(text, "\n");
      const frontmatter = frontmatterOf(lines);
      const title = field(frontmatter, "title").pipe(
        Option.orElse(() => Option.map(Array.head(headingsOf(lines)), (heading) => heading.name)),
        Option.getOrElse(() => page),
      );
      const summary = Option.getOrElse(field(frontmatter, "description"), () => "");
      return `| [${page}](../../${xstate.location}/docs/${page}) | ${escapeCell(title)} | ${lines.length} | ${escapeCell(summary)} |`;
    }),
  );
  const xstateIndex = Array.join(
    Array.flatten([
      [
        "# XState documentation index",
        "",
        GENERATED,
        "",
        `${xstate.name}@${xstate.version} ships these pages in \`${xstate.location}/docs/\`, written for that version. Each row is one page; the pages are short, so read the matching page whole. Start with \`index.md\` (reading order), \`agents.md\` (agent guide), and \`xstate-v5-to-v6.md\` (differences from v5). \`docs/api-stability.json\` classifies every export as public, experimental, or internal. Declarations are in \`${xstate.location}/dist/\`.`,
        "",
        "For Effect-backed actors, see [the @xstate/effect index](../xstate-effect/index.md).",
        "",
        "| Page | Title | Lines | Summary |",
        "| --- | --- | ---: | --- |",
      ],
      rows,
      [""],
    ]),
    "\n",
  );

  const readme = yield* fs.readFileString(path.join(effect.dir, "README.md"));
  const readmeLines = String.split(readme, "\n");
  const topics = headingsOf(readmeLines);
  const effectIndex = Array.join(
    Array.flatten([
      [
        "# @xstate/effect documentation index",
        "",
        GENERATED,
        "",
        `${effect.name}@${effect.version} documents itself in [README.md](../../${effect.location}/README.md). Line ranges refer to that file; read only the matching range. Declarations are in \`${effect.location}/dist/\`. For XState itself, see [the XState index](../xstate/index.md).`,
        "",
      ],
      topicTable(topics, readmeLines.length),
      [""],
    ]),
    "\n",
  );

  const outputs: ReadonlyArray<Output> = [
    { file: ".agent_sources/xstate/index.md", text: xstateIndex },
    { file: ".agent_sources/xstate-effect/index.md", text: effectIndex },
  ];
  if (check) {
    const stale = yield* Effect.filter(outputs, ({ file, text }) =>
      fs.readFileString(path.join(repo, file)).pipe(
        Effect.map((current) => current !== text),
        Effect.orElseSucceed(() => true),
      ),
    );
    if (Array.isReadonlyArrayNonEmpty(stale)) {
      return yield* new StaleXStateIndex({ files: Array.map(stale, ({ file }) => file) });
    }
    return `XState indexes match ${xstate.name}@${xstate.version} and ${effect.name}@${effect.version}`;
  }
  yield* Effect.forEach(
    outputs,
    ({ file, text }) =>
      fs
        .makeDirectory(path.dirname(path.join(repo, file)), { recursive: true })
        .pipe(Effect.andThen(replaceFile(path.join(repo, file), text))),
    { discard: true },
  );
  return `Indexed ${rows.length} XState pages and ${topics.length} @xstate/effect topics`;
});

const command = Command.make(
  "index-xstate-docs",
  {
    check: Flag.Boolean("check").pipe(
      Flag.withDescription("Fail when an index does not match the installed packages"),
      Flag.withDefault(false),
    ),
  },
  (input) =>
    indexXStateDocs(input).pipe(
      Effect.flatMap(Effect.logInfo),
      Effect.tapErrorTag(
        ["XStateNotInstalled", "WorkspaceUnreadable", "StaleXStateIndex"],
        (error) => Effect.logError(error.message),
      ),
    ),
).pipe(Command.withDescription("Index the documentation the installed XState packages ship"));

// Logs go to stderr so stdout stays free for results.
const logger = Logger.layer([Logger.withConsoleError(Logger.formatLogFmt)]);

Command.run(command, { version: "0.0.0" }).pipe(
  Effect.provide(Layer.mergeAll(logger, NodeServices.layer)),
  NodeRuntime.runMain,
);
